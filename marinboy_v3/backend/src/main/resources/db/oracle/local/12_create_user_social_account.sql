-- 기존 MB_USER의 소셜 식별자를 별도 테이블로 옮겨 제공자 여러 개를 연결할 수 있게 합니다.
DECLARE
    SOCIAL_TABLE_COUNT NUMBER;
    LEGACY_COLUMN_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO SOCIAL_TABLE_COUNT
    FROM USER_TABLES
    WHERE TABLE_NAME = 'MB_USER_SOCIAL_ACCOUNT';

    IF SOCIAL_TABLE_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE MB_USER_SOCIAL_ACCOUNT (
                ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                USER_ID NUMBER NOT NULL,
                PROVIDER VARCHAR2(30 CHAR) NOT NULL,
                SOCIAL_ID VARCHAR2(160 CHAR) NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT FK_MB_USER_SOCIAL_USER
                    FOREIGN KEY (USER_ID) REFERENCES MB_USER (ID) ON DELETE CASCADE,
                CONSTRAINT UQ_MB_USER_SOCIAL_PROVIDER UNIQUE (USER_ID, PROVIDER),
                CONSTRAINT UQ_MB_USER_SOCIAL_ID UNIQUE (PROVIDER, SOCIAL_ID)
            )
        ]';
    END IF;

    SELECT COUNT(*) INTO LEGACY_COLUMN_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'MB_USER' AND COLUMN_NAME = 'SOCIAL_PROVIDER';

    IF LEGACY_COLUMN_COUNT = 1 THEN
        EXECUTE IMMEDIATE q'[
            INSERT INTO MB_USER_SOCIAL_ACCOUNT (USER_ID, PROVIDER, SOCIAL_ID)
            SELECT U.ID, U.SOCIAL_PROVIDER, U.SOCIAL_ID
            FROM MB_USER U
            WHERE U.SOCIAL_PROVIDER IS NOT NULL
              AND U.SOCIAL_ID IS NOT NULL
              AND NOT EXISTS (
                  SELECT 1
                  FROM MB_USER_SOCIAL_ACCOUNT A
                  WHERE A.PROVIDER = U.SOCIAL_PROVIDER
                    AND A.SOCIAL_ID = U.SOCIAL_ID
              )
        ]';

        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE MB_USER DROP CONSTRAINT UQ_MB_USER_SOCIAL';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -2443 THEN
                    RAISE;
                END IF;
        END;

        EXECUTE IMMEDIATE 'ALTER TABLE MB_USER DROP (SOCIAL_PROVIDER, SOCIAL_ID)';
    END IF;
END;
/

COMMIT;
