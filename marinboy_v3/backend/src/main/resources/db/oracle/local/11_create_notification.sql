-- 기존 예약·사용자 데이터를 유지하면서 관리자 알림 테이블만 추가합니다.
CREATE TABLE MB_NOTIFICATION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESERVATION_ID NUMBER NOT NULL,
    ADMIN_ID NUMBER NOT NULL,
    MESSAGE VARCHAR2(255 CHAR) NOT NULL,
    IS_READ NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_MB_NOTIFICATION_RESERVATION
        FOREIGN KEY (RESERVATION_ID) REFERENCES MB_RESERVATION (ID) ON DELETE CASCADE,
    CONSTRAINT FK_MB_NOTIFICATION_ADMIN
        FOREIGN KEY (ADMIN_ID) REFERENCES MB_USER (ID) ON DELETE CASCADE,
    CONSTRAINT CK_MB_NOTIFICATION_READ CHECK (IS_READ IN (0, 1))
);

CREATE INDEX IX_MB_NOTIFICATION_ADMIN_READ
    ON MB_NOTIFICATION (ADMIN_ID, IS_READ, CREATED_AT);

-- 생성 결과와 관리자별 안 읽은 알림 건수를 확인합니다.
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'MB_NOTIFICATION';
SELECT ADMIN_ID, COUNT(*) AS UNREAD_COUNT
FROM MB_NOTIFICATION
WHERE IS_READ = 0
GROUP BY ADMIN_ID;
