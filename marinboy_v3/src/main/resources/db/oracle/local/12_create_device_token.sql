-- 기존 데이터를 유지하면서 모바일 푸시 토큰 테이블만 추가합니다.
CREATE TABLE MB_DEVICE_TOKEN (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADMIN_ID NUMBER NOT NULL,
    PUSH_TOKEN VARCHAR2(255 CHAR) NOT NULL,
    PLATFORM VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_MB_DEVICE_TOKEN UNIQUE (PUSH_TOKEN),
    CONSTRAINT FK_MB_DEVICE_TOKEN_ADMIN
        FOREIGN KEY (ADMIN_ID) REFERENCES MB_USER (ID) ON DELETE CASCADE,
    CONSTRAINT CK_MB_DEVICE_TOKEN_PLATFORM CHECK (PLATFORM IN ('ANDROID', 'IOS'))
);

CREATE INDEX IX_MB_DEVICE_TOKEN_ADMIN ON MB_DEVICE_TOKEN (ADMIN_ID, UPDATED_AT);

